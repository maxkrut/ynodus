const SUBDIVISION_FLAG_COUNTRIES: Record<string, string> = {
  ENG: "gb-eng",
  SCT: "gb-sct",
  SCO: "gb-sct",
  WLS: "gb-wls",
};

const regionNameCache = new Map<Locale, Intl.DisplayNames | null>();

export function countryName(code: string, locale: Locale): string {
  const explicit = COUNTRY_NAMES[locale][code] ?? COUNTRY_NAMES.en[code];
  if (explicit) return explicit;
  const iso2 = ISO3_TO_ISO2[code];
  const regionNames = regionDisplayNames(locale);
  const name = iso2 && regionNames ? (regionNames.of(iso2) ?? code) : code;
  return name.replaceAll("\u2014", "-");
}

function regionDisplayNames(locale: Locale): Intl.DisplayNames | null {
  if (regionNameCache.has(locale)) return regionNameCache.get(locale) ?? null;
  const names =
    typeof Intl.DisplayNames === "function"
      ? new Intl.DisplayNames([locale], { type: "region" })
      : null;
  regionNameCache.set(locale, names);
  return names;
}

export function countryFlag(code: string, locale: Locale): string {
  const flagId = SUBDIVISION_FLAG_COUNTRIES[code] ?? ISO3_TO_ISO2[code]?.toLowerCase();
  if (!flagId || flagId === "an" || !/^[a-z]{2}(?:-[a-z]{3})?$/.test(flagId)) {
    return `<span class="flag-missing" aria-hidden="true">◆</span>`;
  }
  const label = `${countryName(code, locale)} ${translate(locale, "flag")}`;
  return `<span class="fi fi-${flagId}" role="img" aria-label="${escapeHtml(label)}"></span>`;
}
